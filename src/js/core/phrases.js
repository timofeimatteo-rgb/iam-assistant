export function say(kind, vars = {}) {
  const list = P[kind] || P.idle;
  let s = list[Math.floor(Math.random() * list.length)];
  const name = vars.name ? ', ' + vars.name : '';
  return s.replace('{name}', name).replace('{min}', vars.min ?? '');
}
